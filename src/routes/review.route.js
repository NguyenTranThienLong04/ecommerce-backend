const express=require("express");
const router=express.Router();
const reviewController=require("../controllers/review.controller");
const authMiddleware=require("../middlewares/auth.middleware");
const adminMiddleware=require("../middlewares/admin.middleware");
const validate = require("../middlewares/validate.middleware");
const schema = require("../validators/review.validator");
router.post("/",authMiddleware,validate(schema.create),reviewController.createReview);
router.get("/variant/:idVariant",validate(schema.list),reviewController.getReviewsByVariant);
router.patch("/:id",authMiddleware,validate(schema.update),reviewController.updateReview);
router.patch("/status/:id",authMiddleware, adminMiddleware,validate(schema.status),reviewController.updateReviewStatus);
module.exports=router;
